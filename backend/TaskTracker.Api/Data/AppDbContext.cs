using Microsoft.EntityFrameworkCore;
using TaskTracker.Api.Entities;

namespace TaskTracker.Api.Data;

public class AppDbContext(DbContextOptions<AppDbContext> options) : DbContext(options)
{
    public DbSet<Project> Projects => Set<Project>();
    public DbSet<ProjectTask> Tasks => Set<ProjectTask>();

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.Entity<Project>(project =>
        {
            project.Property(p => p.Name).HasMaxLength(Project.NameMaxLength);
            project.Property(p => p.Description).HasMaxLength(Project.DescriptionMaxLength);

            // The creation date is generated by PostgreSQL, not by application code.
            project.Property(p => p.CreatedAt).HasDefaultValueSql("now()");
        });

        modelBuilder.Entity<ProjectTask>(task =>
        {
            task.Property(t => t.Title).HasMaxLength(ProjectTask.TitleMaxLength);

            // The status is stored as text ("Todo", "InProgress", "Done"): readable directly in SQL.
            task.Property(t => t.Status).HasConversion<string>().HasMaxLength(20);

            // A task belongs to exactly one project; deleting the project deletes its tasks.
            task.HasOne(t => t.Project)
                .WithMany(p => p.Tasks)
                .HasForeignKey(t => t.ProjectId)
                .OnDelete(DeleteBehavior.Cascade);

            // Stored as text like the status. The database default gives existing rows "Normal" when the
            // column is added. The sentinel tells EF that only "Normal" means "not set": without it, EF
            // would treat "Low" (the enum's zero value) as not set and silently store "Normal" instead.
            task.Property(t => t.Priority)
                .HasConversion<string>()
                .HasMaxLength(20)
                .HasDefaultValue(ProjectTaskPriority.Normal)
                .HasSentinel(ProjectTaskPriority.Normal);
        });
    }
}
